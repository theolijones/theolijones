import React, { useState } from 'react';
import { NavLink, useNavigate } from 'react-router-dom';
import { useAuth } from './AuthContext';

const navItems = [
  { to: '/', label: 'Dashboard', icon: ChartIcon },
  { to: '/companies', label: 'Companies', icon: BuildingIcon },
  { to: '/infractions', label: 'Infractions', icon: AlertIcon },
  { to: '/reports', label: 'Reports', icon: FileIcon },
  { to: '/users', label: 'Users', icon: UsersIcon, admin: true },
  { to: '/mailing-list', label: 'Mailing List', icon: MailIcon, admin: true },
];

